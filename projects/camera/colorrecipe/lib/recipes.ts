export function flatHsl(overrides: Record<string, Partial<Omit<HslBand, "id" | "label" | "swatch">>> = {}): HslBand[] {
  return HSL_BAND_META.map((meta) => ({
    ...meta,
    hue: 0,
    saturation: 0,
    luminance: 0,
    ...overrides[meta.id],
  }));
}

export function flatCurves(
  overrides: Partial<Record<keyof ToneCurves, ToneCurves["rgb"]>> = {},
): ToneCurves {
  const identity = [
    { x: 0, y: 0 },
    { x: 50, y: 50 },
    { x: 100, y: 100 },
  ];
  return {
    rgb: overrides.rgb ?? identity,
    r: overrides.r ?? identity,
    g: overrides.g ?? identity,
    b: overrides.b ?? identity,
  };
}

